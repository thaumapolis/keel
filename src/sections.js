import { columnBounds } from "./columns.js";
import { gaussLegendre } from "./quad.js";

/**
 * sections.js -- the hydrostatics of a HEELED hull, integrated from the hull form.
 *
 * This is the method the project depends on, and it replaced a station-summing
 * implementation that could not express heel at all. The predecessor computed the
 * waterplane's transverse second moment from half-breadths at a HORIZONTAL cut,
 * and heelState() handed it the same unrotated stations whatever the angle, so
 * the waterplane inertia did not change as the ship heeled (observed: 21.55989 at
 * both 0 rad and 0.5 rad). Every GZ past a few degrees inherited that: measured
 * against this file, it was 35% low at 20 deg, 50% low at 30 deg, and NEGATIVE at
 * 45 deg where the true arm is still slightly positive -- it told the user the
 * ship was capsizing at an angle where the geometry says it rights itself.
 *
 * Why this formulation. A heeled section's submerged region is not single-valued
 * in body z: once the keel edge emerges, a horizontal line inside it meets the
 * boundary twice. Any representation that stores a section as "half-breadth as a
 * function of height" cannot express that, and being correct past the deck-edge
 * angle is the entire point. So the section is described the other way round --
 * for each column at body |x|, the range of z in which the hull exists -- and the
 * waterline simply cuts that range. The z range comes from inverting the declared
 * hull form, not from a polyline approximation of it, so the only errors left are
 * column and station spacing, both under direct control and both measured.
 *
 * Conventions, matching src/hull.js (x starboard, y forward, z up from keel,
 * right-handed, so POSITIVE heel tips STARBOARD down):
 *
 *     worldX = bodyX*cos + bodyZ*sin
 *     worldZ = -bodyX*sin + bodyZ*cos
 *
 * The sanity check on that reading: the starboard keel point (bodyX = +h,
 * bodyZ = 0) maps to worldZ = -h*sin < 0 for heel > 0, i.e. below the water
 * surface at worldZ = 0, so water covers more of the x > 0 side. The waterplane
 * in body coordinates is therefore
 *
 *     bodyZ <= (w + bodyX*sin)/cos
 *
 * with w the waterline height at the centreline.
 *
 * GZ is the horizontal separation, in the WORLD frame where the water surface is
 * level, between the buoyancy centre and the centre of gravity:
 *
 *     GZ = (B_worldX - G_worldX) * V / V0
 *
 * The V/V0 factor is not decoration. GZ is a righting ARM, and the righting
 * MOMENT is rho*g*V*GZ; comparing moments at a fixed displacement makes the arm
 * the world offset scaled by the volume ratio. For a wall-sided hull V falls as
 * cos(theta) while the offset grows, so dropping the factor changes the shape of
 * the curve, not just its scale.
 *
 * Accuracy, measured two ways. Upright volume against an independent
 * 200001-point double Simpson of the hull form: 0.0002% at nu=nx=801, and the
 * error falls as the spacing (nu=31 -> -0.20%, 61 -> -0.01%, 121 -> +0.04%).
 * Against the naive closed form L*B*D*blockCoefficient it plateaus at +0.048%
 * however fine the grid: that plateau is NOT this file's error, it is
 * hull.js's block-coefficient solver, whose meanVerticalProfileAt(u) uses a
 * left-endpoint rectangle rule where the taper is steepest at the keel, so the
 * exponent it solves for is off. The closed form is the approximation.
 *
 * Small-angle behaviour is the sign test: GZ must tend to GM*sin(theta) for a
 * STABLE hull, so GZ/sin(theta) -> GM > 0.
 */

/**
 * Gauss-Legendre nodes and weights on [-1, 1].
 *
 * Generated by Newton iteration on the Legendre polynomial rather than
 * transcribed, and checked on load. The reason is a specific mistake: a
 * hand-copied table here summed its weights to 2.4488 instead of the required 2
 * -- an 11% error, catchable by the single cheapest test there is ("integrate the
 * constant 1") -- and because the rule fed the block-coefficient calibration,
 * every hull built from it displaced about 22% wrong while still looking exactly
 * like a hull. Hardcoded constants are code and need the same provenance.
 */
/**
 * Everything about a heel angle that does NOT depend on the waterline: the
 * column x positions and their z ranges, per station, with Simpson weights.
 *
 * This is separated from the waterline evaluation because recomputing it was the
 * cost of the whole stability model. Solving for the floating waterline needs
 * ~50 quadrature evaluations, and doing the shape work each time cost 3.46 ms per
 * evaluation and 145 ms per heel angle -- 8.7 s for a 60-sample GZ curve, which
 * cannot run in front of a user. Built once per hull and angle, the waterline
 * solve becomes arithmetic and the curve drops to the tens of milliseconds.
 */
/**
 * Resolution defaults, set from measurement. See the two "measured on its own"
 * checks in tests/hydrostatics.test.mjs for the method and the numbers.
 *
 * The two directions are independent, so each has to be measured with the other
 * pinned; summed, the larger term hides the smaller one and the trend is
 * unreadable. Holding nx = 65, the longitudinal term at Cb = 0.62 falls
 * 5.8e-4 -> 2.1e-4 -> 2.7e-5 -> 1.7e-5 over nu = 15 -> 511. Holding nu = 63, the
 * transverse term falls 5.4e-4 -> 1.3e-4 -> 5.3e-6 over nx = 65 -> 257. The
 * transverse direction is the limiting one, which is why the defaults spend the
 * budget there (nu = 122 stations, nx = 481 columns) rather than going square:
 * that pair gives 7.3e-6 / 1.2e-5 / 2.1e-6 relative volume error at Cb =
 * 0.40 / 0.62 / 0.78 for ~140 ms of shape building, which is comfortably inside
 * the 0.1% the model is quoted to and cheap enough to run for every heel angle.
 *
 * The column-boundary inversion (50 bisection steps above) is NOT a limiting
 * term. Measured at 8 / 16 / 26 / 39 / 50 / 64 / 90 steps across five
 * resolutions and two block coefficients, the answer is identical from 26 steps
 * onward and 7.3e-6 -> 7.9e-6 at the defaults between 50 and 200 steps. A plateau
 * here once had me blaming this inversion for error the transverse quadrature
 * owned; the way out was to vary one thing at a time.
 */
export function buildHeel(hull, angleRad, { nu = 122, nx = 481 } = {}) {
  const sinT = Math.sin(angleRad);
  const cosT = Math.cos(angleRad);

  // Longitudinal quadrature: Gauss-Legendre on s = 2u - 1, so the stations come
  // in symmetric pairs about midships. `nu` is rounded up to an even order by
  // gaussLegendre and the actual count is reported as stationCount; callers must
  // use stations.length rather than assuming their own nu, because asking for an
  // odd order silently yields nu + 1 stations. Measured, before that was made
  // explicit: passing an odd nu produced -5.2% volume where the even neighbour
  // gave 0.011%.

  //
  // Not Simpson, and the measurement that decided it is worth keeping. Simpson in
  // u converged at first order and the error was wholly longitudinal: holding nx
  // fixed at 121 and 1201 gave the same answer to four figures while nu varied
  // (nu 11/61/241/601 -> -5.08%, -0.71%, -0.155%, -0.055% at block coefficient
  // 0.78). The reason is the taper itself: (1 - s^2)^(e/2) has vertical tangents
  // at both ends, so the integrand is not smooth at u = 0 and u = 1 and
  // Simpson's fourth-derivative error bound is void exactly there. Gauss-Legendre
  // puts no node on the endpoints and absorbs the algebraic endpoint behaviour:
  // measured 3.6e-5 at 40 nodes against Simpson's 2.0e-4 at 2401, and it keeps
  // improving (8.6e-8 at 640) instead of stalling.
  //
  // Also free of a resolution subtlety Simpson had: the old code required an odd
  // nu so the intervals paired, which is a constraint a caller could violate and
  // which bought nothing once the rule was replaced.
  const longitudinal = gaussLegendre(nu);
  // Transverse quadrature, also Gauss-Legendre, on x = halfBeam * t for t in
  // [-1, 1]. Simpson across the beam was the original choice and it was the
  // better one until the longitudinal rule stopped limiting the error; then the
  // transverse direction became the limit, and it is first-order-ish here for the
  // analogous reason. columnBounds flips between three regimes -- outside the
  // hull, inside the tumblehome, inside the maximum breadth -- as |x| crosses the
  // deck-edge and maximum breadths, so the column height has derivative jumps at
  // three interior points that no uniform grid resolves faster than O(h^2).
  // Measured at block coefficient 0.4 with nu = 402: nx 401/801/1601/3201 gave
  // 1.12e-2%, 4.37e-3%, 1.81e-3%, 4.07e-4% -- halving the error for each halving
  // of the spacing, so the cost of doing better by refinement alone is prohibitive.
  //
  // GL does not need the knots to be resolved, because it never evaluates at a
  // prescribed point and absorbs the kink into its own quadrature error, which
  // decays geometrically on each smooth piece. The beam direction also has no
  // endpoint singularity, unlike the taper, so the gain is larger here.
  const halfBeam = hull.beam / 2;
  const transverse = gaussLegendre(nx);
  const xs = transverse.nodes.map((t) => halfBeam * t);
  const wx = transverse.weights.map((weight) => weight * halfBeam);

  const stations = [];
  // Iterate the rule, not the requested nu: gaussLegendre coerces an odd order up
  // to even, so its node count can exceed nu by one. Reading nodes[i] for i up to
  // nu then walks one past the array, and a stale `undefined` weight silently
  // produced -515% volume -- the sign of an index misalignment rather than an
  // approximation, though it looked like bad convergence until the weight sum was
  // printed.
  for (let i = 0; i < longitudinal.nodes.length; i += 1) {
    const s = longitudinal.nodes[i];
    const u = (s + 1) / 2;
    const bounds = xs.map((x) => columnBounds(hull, u, Math.abs(x)));
    // Weight for the integral over u: the rule is stated on [-1, 1], and
    // du/ds = 1/2.
    stations.push({ weight: longitudinal.weights[i] / 2, bounds });
  }
  return {
    stations,
    xs,
    wx,
    sinT,
    cosT,
    length: hull.length,
    // The order actually used, which differs from the requested nu when nu is odd.
    order: stations.length,
  };
}

/**
 * Volume and buoyancy centre (body frame) for a precomputed heel at centreline
 * waterline w.
 *
 * For a column spanning body z in [bottom, top], the waterplane cuts it at
 * zTop = min(top, (w + x*sin)/cos), so the submerged height is
 * max(0, zTop - bottom) and the first moments follow in closed form:
 * area = height, moment about z = 0 is (zTop^2 - bottom^2)/2, and the x moment is
 * area * x. Integrating across the beam and along the hull is Simpson both ways
 * on the same columns the shape was resolved on, so the volume, the vertical
 * centroid and the transverse shift cannot disagree with each other the way three
 * independent formulas can.
 */
/**
 * Volume and buoyancy centre for a precomputed heel, when the water surface is
 * the world-horizontal plane at height w on the centreline.
 *
 * RETURNS BODY-FRAME COORDINATES, and the whole function is a carepath between
 * two frames, so both are stated in the name of every intermediate.
 *
 *   world xw =  x*cosT + z*sinT
 *   world zw = -x*sinT + z*cosT
 *
 * Submerged part of a column: body z in [bottom, min(top, t)] where
 * t = (w + x*sinT)/cosT is the body-frame height of the water surface over that
 * column. A slice of body dz occupies world height cosT*dz, so dV = cosT*h*dx*dz;
 * the cosT is a constant scale and cancels in every centroid, but it is kept so
 * the intermediate sums are actual volumes and not mixed units.
 *
 * THE CENTROID IS TAKEN IN THE WORLD FRAME AND THEN ROTATED BACK, and that is
 * the fix for a bug that produced a buoyancy centre 8 m above the keel on a 2.4 m
 * hull. The previous version computed the first moment of the submerged volume
 * about the BODY origin and divided by cosT, i.e. it assumed the world moment
 * divided by cosT gives back a body coordinate. It does not: the moment of a
 * rotated body about the body axes is not the rotation of its moment about the
 * world axes, because the slice heights themselves are being measured in the
 * wrong frame. The error grows like 1/cosT, which is 1.0 at 0 deg, 1.3 at 40 deg,
 * 2.0 at 60 deg and unbounded at 90 -- so the artefact was invisible upright, mild
 * at moderate heel, and catastrophic exactly where stability matters most.
 * Measured: bz reported 8.00 at 60 deg against a hull whose deck is at 2.40.
 *
 * Doing it correctly: accumulate the world-frame first moments of each column,
 * divide by volume to get the world centroid, then rotate that single point back
 * by -heel. One rotation, at the end, of a point -- not of a moment.
 */
export function heelAt(heel, w) {
  const { stations, xs, wx, sinT, cosT, length } = heel;
  let volume = 0;
  let bodyX = 0;
  let bodyZ = 0;
  let worldX = 0;
  let worldZ = 0;
  for (const station of stations) {
    let aVolume = 0;
    let aBodyX = 0;
    let aBodyZ = 0;
    let aWorldX = 0;
    let aWorldZ = 0;
    for (let j = 0; j < xs.length; j += 1) {
      const bounds = station.bounds[j];
      if (!bounds) continue;
      const x = xs[j];
      const t = (w + x * sinT) / cosT;
      const top = Math.min(bounds.top, t);
      const bottom = bounds.bottom;
      const height = top - bottom;
      if (height <= 0) continue;
      const column = wx[j] * cosT * length;
      // int over body z of the slice, with world x and z substituted.
      //   int dz              = h
      //   int z dz            = (top^2 - bottom^2)/2
      //   int z^2 dz          = (top^3 - bottom^3)/3
      const m0 = height;
      const m1 = (top * top - bottom * bottom) / 2;
      const vol = column * m0;
      // xw = x*cosT + z*sinT, so int xw d(body z) = x*cosT*m0 + sinT*m1.
      // zw = -x*sinT + z*cosT, so int zw d(body z) = -x*sinT*m0 + cosT*m1.
      aVolume += vol;
      aBodyX += column * (x * m0);
      aBodyZ += column * m1;
      aWorldX += column * (x * cosT * m0 + sinT * m1);
      aWorldZ += column * (-x * sinT * m0 + cosT * m1);
    }
    volume += station.weight * aVolume;
    bodyX += station.weight * aBodyX;
    bodyZ += station.weight * aBodyZ;
    worldX += station.weight * aWorldX;
    worldZ += station.weight * aWorldZ;
  }
  if (!(volume > 1e-12)) return null;
  // Accumulate the BODY-frame first moments as well, and return the body centroid
  // -- which is what bx/bz are documented to be -- plus the world centroid, so no
  // caller has to rotate anything. The two are related by the forward transform
  //   xw = bx*cosT + bz*sinT,  zw = -bx*sinT + bz*cosT
  // and the righting arm needs only the world one.
  //
  // Why both, and not just the world: getting this wrong twice in a row was
  // caused by returning one and letting a caller rotate it, which silently
  // rotated twice. The exact rectangular-barge check settles the frame -- at any
  // heel the body-frame buoyancy height is measured from the keel and must rise
  // monotonically toward the section's own centroid, and at 0 deg it is exactly
  // T/2 by inspection (draft 1.32 gives 0.66). Rotating the body centroid once
  // into world coordinates reproduces that; the moment-based route that produced
  // "bz = 8.0 m on a 2.4 m hull" was measuring the moment about the wrong frame's
  // axes and dividing by cosT.
  return {
    volume,
    bx: bodyX / volume,
    bz: bodyZ / volume,
    worldCenter: { x: worldX / volume, z: worldZ / volume },
  };
}

/**
 * Why a target displacement cannot be reached at a given heel.
 *
 * "It will not float" is two different facts and the UI has to say them apart.
 * Too full means the hull is already carrying more than the whole hull holds --
 * it was never going to float at ANY angle. Beyond reach means the hull floats
 * fine, just not heeled this far. Returning the reason rather than null keeps
 * callers from having to infer it from angle, which they cannot do correctly:
 * the reachable envelope is not symmetric, and measured on a 40%-draft box-form
 * hull the floatable range runs 0-90.9 deg on one side of the keel-down regime
 * and comes back above 179 deg, because the hull is a sealed box and righting
 * and floating are genuinely separate properties.
 */
export const FloatFailure = Object.freeze({
  TOO_FULL: "too full",
  BEYOND_REACH: "beyond reach",
  NOTHING_TO_INTEGRATE: "nothing to integrate",
});

/**
 * The floating waterline at a heel angle, for a target displacement.
 *
 * Returns { waterline } or { failure, maxVolume } -- never null, because null
 * threw away the distinction above. Callers that want an exception wrap this.
 *
 * volume is strictly increasing in w between "no column wet" and "every column
 * fully wet", and above the fully-wet height it is constant, so the bracket's
 * upper end must be derived from where monotonicity stops, not from the hull's
 * nominal size: fully wet needs w >= max over columns of (top*cos - x*sin), which
 * for a hull of depth D and half-beam h is D*cos + h*sin over cos, i.e.
 */
/**
 * The floating waterline at a heel angle, for a target displacement.
 *
 * Returns { waterline } or { failure, maxVolume } -- never null, because null
 * threw away the distinction between "this hull holds less than that" and "not at
 * this angle", and the UI has to say them apart.
 *
 * BRACKETING. w is the height of the world-horizontal water plane measured on the
 * centreline, and for a heeled ship that plane can pass far above the hull's own
 * top, so w is NOT confined to [0, depth] -- an earlier version assumed it was and
 * the bracket then excluded the solution at small heel angles, reporting "beyond
 * reach" at 0 deg, and wherever it did converge it returned bx = 0 at every angle
 * because the plane was never free to move across the hull.
 *
 * Nor is the useful lower limit the lowest column bottom. Column bottoms are
 * computed in BODY frame; a column at body x sits at world height offset by
 * x*sinT/cosT, so the w at which a column STARTS to wet is
 *
 *   cosT > 0:  w > bottom*cosT - x*sinT     (rising in w)
 *   cosT < 0:  w < bottom*cosT - x*sinT     (falling in w)
 *
 * and the bracket must span from BELOW the smallest of those to ABOVE the largest.
 * Taking "largest" as the near end -- which is what max(bottom*cosT - x*sinT) is,
 * and which sits at the deck for an upright hull -- put the whole bracket above
 * every solution for a ship floating at partial depth: measured at 0 deg with the
 * target holding 55% of depth, the bracket started at 2.4 and volume came back 0,
 * so maxVolume 0 was reported for a hull that floats perfectly well.
 *
 * So: derive a first guess from the column bottoms, then EXPAND BOTH ENDS until
 * the target volume is bracketed. Termination is guaranteed because submerged
 * volume tends to 0 as w goes to the dry end and to the whole hull as w goes to
 * the wet end, monotonically in between (the single-interval property of
 * columns.js is what makes it monotone).
 */
export function floatWaterline(heel, targetVolume) {
  const { xs, stations, sinT, cosT } = heel;
  let low = Infinity;
  let high = -Infinity;
  for (const station of stations) {
    for (let j = 0; j < xs.length; j += 1) {
      const bounds = station.bounds[j];
      if (!bounds) continue;
      const f = bounds.bottom * cosT - xs[j] * sinT;
      if (f < low) low = f;
      if (f > high) high = f;
    }
  }
  if (!(low < high)) {
    // No column at all is wet at any waterline: the heel data has nothing to
    // integrate. Distinct from TOO_FULL, which means there is something to
    // integrate and it is not enough.
    return { failure: FloatFailure.NOTHING_TO_INTEGRATE, maxVolume: 0 };
  }

  // lo is the lowest bottom EXACTLY, not one margin below it, and that is not
  // sloppiness. A keel column has bottom = 0, so "lowest bottom minus a margin"
  // is negative, and heelAt returns null below the hull rather than 0 -- which
  // the expansion loop below reads as "the dry end is comfortably under target"
  // and stops expanding. The bracket then does not contain the solution, the
  // bisection converges near w = 0 where heelAt is null, and a hull floating
  // happily at 55% of its depth is reported as unable to float at all. Every
  // column is wet at w = low by definition, so the volume here is positive, and
  // it is still the dry end of the bracket: at most a hair under target.
  let lo = low;
  let hi = high + Math.max(1, high - low);

  const volumeAt = (w) => heelAt(heel, w)?.volume ?? 0;
  // Volume increases with w below 90 deg of heel and DECREASES above it: past 90
  // the body-to-world map reverses orientation, so raising the plane dries the
  // hull. Measured on one hull, volume(w) ran 0 -> 77.03 over w in [0, 2.40] at
  // 89.9 deg and the mirror 77.03 -> 0 over [-2.00, 2.00] at 90.01 deg. Expressing
  // the search as "the boundary between enough and not enough", in terms of the
  // orientation rather than of lo/hi, makes both signs of cosT land on the
  // waterline instead of being driven to the dry end -- an earlier version assumed
  // increasing, drove w to the dry end past 90 deg, reported maxVolume 0.000, and
  // confidently declared a floating hull "TOO FULL to float".
  const increasing = cosT > 0;
  const enough = (w) => volumeAt(w) >= targetVolume * (1 - 1e-9);
  const wetEnd = () => (increasing ? hi : lo);

  // Expand until the wet end actually holds the target.
  for (let step = 0; step < 80; step += 1) {
    if (enough(wetEnd())) break;
    if (step === 79) {
      return { failure: FloatFailure.TOO_FULL, maxVolume: volumeAt(wetEnd()) };
    }
    if (increasing) hi += Math.max(1, Math.abs(hi)) * 0.5;
    else lo -= Math.max(1, Math.abs(lo)) * 0.5;
  }
  // Expand the dry end until volume there is under the target, so the boundary is
  // genuinely inside the bracket rather than below the low end.
  for (let step = 0; step < 80; step += 1) {
    const dryEnd = increasing ? lo : hi;
    // Not-enough is only meaningful where there is a solid to measure. heelAt
    // returns null once the plane is off the hull entirely, and treating that as
    // "under target" is what let a bracket that missed the solution pass this
    // loop untouched.
    if (volumeAt(dryEnd) === 0 || !enough(dryEnd)) break;
    if (step === 79) {
      return { failure: FloatFailure.TOO_FULL, maxVolume: volumeAt(wetEnd()) };
    }
    if (increasing) lo -= Math.max(1, Math.abs(lo)) * 0.5;
    else hi += Math.max(1, Math.abs(hi)) * 0.5;
  }

  // Bisection on the boundary between "not enough" and "enough".
  //
  // The direction is set by the orientation, NOT by which end is numerically
  // larger, and getting this backwards is easy because both readings of the
  // ternary look defensible. The invariant is: lo stays on the not-enough side
  // and hi stays on the enough side, so the interval always contains the crossing.
  // Below 90 deg of heel volume increases with w, so a mid that is enough moves
  // HI down; above 90 deg volume DEcreases with w, so a mid that is enough moves
  // LO up. An earlier revision had the two cases swapped -- `if (enough(mid) ===
  // increasing) lo = mid` -- which pushed lo toward the saturated wet end, and
  // because volume is constant above the hull, the converged w was a point where
  // the volume trivially equals the whole hull. That is how a hull floating at
  // 55% of its depth came back with GZ = 901 metres and a buoyancy centre 6.8 m
  // above the keel on a 2.4 m boat: the "waterline" was 4.8 m, outside the ship,
  // and bz was being extrapolated by the cosT division rather than measured.
  for (let i = 0; i < 60; i += 1) {
    const mid = (lo + hi) / 2;
    if (enough(mid)) hi = mid;
    else lo = mid;
  }
  // hi is the tightest w that still holds the target volume, in both
  // orientations, because the loop above maintains that invariant directly.
  const waterline = hi;
  if (!enough(waterline)) {
    // Unreachable in exact arithmetic once the expansion above succeeded. Guards
    // the bracket itself; the failure it catches is a silently wrong waterline,
    // which is the worst thing this function could hand back.
    return { failure: FloatFailure.BEYOND_REACH, maxVolume: volumeAt(waterline) };
  }
  return { waterline };
}

/**
 * Floating state at a heel angle: the waterline that holds the displacement, and
 * the hydrostatics there. Null means the hull cannot float that way over.
 */
export function floatState(hull, angleRad, targetVolume, options) {
  const heel = buildHeel(hull, angleRad, options);
  const solution = floatWaterline(heel, targetVolume);
  if (solution.failure !== undefined) {
    return { failure: solution.failure, maxVolume: solution.maxVolume };
  }
  const body = heelAt(heel, solution.waterline);
  if (!body) return null;
  return { waterline: solution.waterline, ...body };
}

/**
 * Righting arm at angleRad for a centre of gravity at (0, KG), floating upright
 * at `uprightVolume`. See the header for why the volume ratio multiplies the arm.
 */
export function rightingArmAt(hull, angleRad, KG, uprightVolume, options) {
  const state = floatState(hull, angleRad, uprightVolume, options);
  // Pass the reason through rather than collapsing it to null: "this hull does
  // not float at all" and "not at this angle" need to reach the caller intact.
  if (state === null) return null;
  if (state.failure !== undefined) return { failure: state.failure, maxVolume: state.maxVolume };
  const sinT = Math.sin(angleRad);
  // GZ is the HORIZONTAL distance in the world from the centreline to the buoyancy
  // centre, minus the horizontal offset of the centre of gravity. Both terms are
  // world quantities and heelAt already returns the world centroid -- using the
  // body-frame bx here and rotating it would be a second rotation of the same
  // point, which is how this line produced a GZ of 901 m on a 4 m beam.
  // GZ is the horizontal distance between the buoyancy centre's line of action
  // and the centre of gravity, both measured in the WORLD. The moment arm of the
  // buoyancy force about G is exactly (Bxw - KG*sinT): the buoyancy force is
  // vertical through (Bxw, bzw) and the weight acts at (KG*sinT, KG*cosT) once
  // the ship heels, and the horizontal separation is all a vertical force pair
  // contributes.
  //
  // There is no volume-ratio factor here, and an earlier version multiplied the
  // whole arm by (state.volume / uprightVolume). That ratio is 1 whenever the
  // waterline solve has done its job -- the solve exists precisely to hold
  // displacement constant -- so it could only ever be 1 or a report that the solve
  // failed. Carrying it as a correction made the numbers look adjusted rather than
  // measured, and if the volumes ever genuinely differ the right response is to
  // say so, not to scale the answer.
  const bWorldX = state.worldCenter.x;
  return {
    volume: state.volume,
    waterline: state.waterline,
    gz: bWorldX - KG * sinT,
    body: { bx: state.bx, bz: state.bz },
    worldCenter: state.worldCenter,
  };
}

/**
 * renderGeometry -- the world-frame geometry the 3D view draws, computed from the
 * SAME halfBreadth the hydrostatics integrate.
 *
 * The renderer needs two closed world-space outlines per heel state: the waterplane
 * (where the water surface world z = 0 meets the hull) and the deck sheer (the deck
 * edge, lofted along the hull). Handing the renderer a body-frame mesh and letting
 * it rotate would reproduce the exact class of frame bug this file has been bitten
 * by (double-rotating buoyancy), so the rotation happens HERE, once, in the same
 * convention as heelAt:
 *
 *   world xw =  x*cosT + z*sinT
 *   world zw = -x*sinT + z*cosT      (y unchanged; the world water surface is zw = 0)
 *
 * Waterplane. At heel, a body-frame point is on the water surface when zw = 0,
 * i.e. z_body = x*cosT / sinT... no -- solve zw = 0 for the section height. For a
 * column at body |x| the water cuts it at body height t = (0 + x*sinT)/cosT
 * (the same expression heelAt uses, with w = 0 because the water surface passes
 * through the world origin). The half-breadth of the waterplane at that station is
 * b(u, t). Trace both sides out and back to close the ring.
 *
 * This is the shape that does the righting, so getting it right matters more than
 * getting it cheap; it is checked against the integrated waterplane area.
 */
export function renderGeometry(hull, angleRad, waterline, { nStations = 60, nEdge = 40 } = {}) {
  const sinT = Math.sin(angleRad);
  const cosT = Math.cos(angleRad);
  // waterline is a BODY-frame height measured where the water surface crosses the
  // centreline (body x = 0). heelAt(w) cuts each column at body height
  // t = (waterline + x*sinT)/cosT; the world water surface is zw = 0.
  // Rotate a body point into the world. heelAt's world frame puts the keel-anchored
  // body origin at height (waterline) above the water surface, so a point on the
  // water surface rotates to world z = waterline, not 0. The renderer (and the
  // "submerged iff world z < 0" convention every module uses) wants the water
  // SURFACE at z = 0, so we drop the whole ship by waterline. One offset, applied
  // to everything, so deck, waterplane and buoyancy stay mutually consistent.
  const toWorld = (x, y, z) => ({
    x: x * cosT + z * sinT,
    y,
    z: -x * sinT + z * cosT - waterline,
  });

  // Waterplane ring: for each station, the waterline's half-breadth, then out the
  // starboard side and back the port side.
  const wp = [];
  const stations = [];
  for (let i = 0; i < nStations; i += 1) {
    const u = i / (nStations - 1);
    const y = hull.length * (u - 0.5);
    stations.push({ u, y });
    // The water surface at this station is a line in the body x-z plane. Its
    // widest body |x| where the hull still reaches that height gives the
    // waterplane half-breadth there. Invert halfBreadth(u, z) monotone in z:
    // breadth(x) such that b(u, z_of_x) sits on zw=0. Because the body height of
    // the water at body x is t(x) = (waterline + x*sinT)/cosT, the waterplane edge
    // is where halfBreadth(u, t(x)) = |x| -- found by a short bisection in x.
    const edgeHalfBreadth = waterHalfBreadth(hull, u, waterline, sinT, cosT);
    wp.push({ star: edgeHalfBreadth, y });
  }
  const waterplane = [];
  // starboard edge forward, then port edge back, all on the world surface zw=0.
  for (const s of wp) {
    waterplane.push(toWorld(s.star, s.y, waterlineTAt(hull, s.star, waterline, sinT, cosT)));
  }
  for (let i = wp.length - 1; i >= 0; i -= 1) {
    const s = wp[i];
    waterplane.push(toWorld(-s.star, s.y, waterlineTAt(hull, s.star, waterline, sinT, cosT)));
  }

  // Deck sheer: trace the deck edge (top of the section outline) along the hull,
  // both sides, so the tilt of the topsides reads against the level waterline.
  const deckStarboard = [];
  const deckPort = [];
  for (let i = 0; i <= nEdge; i += 1) {
    const u = i / nEdge;
    const y = hull.length * (u - 0.5);
    const halfB = hull.halfBreadth(u, hull.depth);
    deckStarboard.push(toWorld(halfB, y, hull.depth));
    deckPort.push(toWorld(-halfB, y, hull.depth));
  }
  const deckPolys = [deckStarboard.concat(deckPort.slice().reverse())];

  return { waterplane, deckPolys, toWorld };
}

/** Body height of the water surface above body x, on the zw=0 water plane. */
function waterlineTAt(hull, absX, waterline, sinT, cosT) {
  return (waterline + absX * sinT) / cosT;
}

/**
 * Half-breadth of the waterplane at station u: the |x| where the section's
 * half-breadth equals the body x that the water surface sits at. halfBreadth
 * decreases as we look at narrower z, and the water height t(x) rises with x, so
 * there is one crossing; bisect it. Bounded by the deck half-breadth at this u.
 */
function waterHalfBreadth(hull, u, waterline, sinT, cosT) {
  const deckHalf = hull.halfBreadth(u, hull.depth);
  if (deckHalf <= 0) return 0;
  // At body x, the water sits at body height t(x); the hull's half-breadth down
  // there is halfBreadth(u, t). The waterplane edge is where that breadth reaches
  // x. Define f(x) = halfBreadth(u, t(x)) - x; f > 0 inside the waterplane, < 0
  // outside; bisect the root in [0, deckHalf].
  const f = (x) => {
    const t = (waterline + x * sinT) / cosT;
    if (t <= 0) return -x;
    if (t > hull.depth) return deckHalf; // water overtops the deck: wet to the deck edge
    return hull.halfBreadth(u, t) - x;
  };
  if (f(deckHalf) >= 0) return deckHalf;  // fully wet at this station's deck edge
  let lo = 0, hi = deckHalf;
  for (let i = 0; i < 48; i += 1) {
    const mid = (lo + hi) / 2;
    if (f(mid) > 0) lo = mid; else hi = mid;
  }
  return (lo + hi) / 2;
}
